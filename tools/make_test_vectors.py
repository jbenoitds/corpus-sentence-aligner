#!/usr/bin/env python3
"""Regenerate the test fixtures that need an independent implementation.

* tests/deflate_vectors.hpp  - raw DEFLATE streams produced by Python's zlib
                               (stored, fixed-Huffman, dynamic-Huffman, RLE).
* tests/data/fixture.docx    - a small hand-written Word document that
                               exercises tracked changes, superscript
                               citations, text boxes with fallbacks, field
                               codes, tabs, line breaks and tables.

Only the Python 3 standard library is used. Run from the repository root:
    python3 tools/make_test_vectors.py
"""
import random
import zipfile
import zlib


def raw_deflate(data, level, strategy=zlib.Z_DEFAULT_STRATEGY):
    c = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
    return c.compress(data) + c.flush()


def cpp_bytes(b):
    return 'std::string("' + "".join("\\x%02x" % x for x in b) + '", %d)' % len(b)


def write_deflate_vectors(path):
    random.seed(7)
    words = ("le sommeil sleep wellbeing étude study participants "
             "questionnaire réponses answers confidential").split()
    text = " ".join(random.choice(words) for _ in range(600)).encode("utf-8")
    vectors = [
        ("stored", b"Hello, stored block!", raw_deflate(b"Hello, stored block!", 0)),
        ("fixed", b"abcabcabcabcabc hello hello hello",
         raw_deflate(b"abcabcabcabcabc hello hello hello", 9, zlib.Z_FIXED)),
        ("dynamic", text, raw_deflate(text, 9)),
        ("empty", b"", raw_deflate(b"", 6)),
        ("rle", b"a" * 5000, raw_deflate(b"a" * 5000, 9, zlib.Z_RLE)),
    ]
    lines = [
        "// Generated by tools/make_test_vectors.py with Python's zlib (raw DEFLATE, wbits=-15).",
        "#pragma once",
        "#include <string>",
        "#include <vector>",
        "struct DeflateVector { const char* name; std::string plain; std::string packed; };",
        "inline std::vector<DeflateVector> deflate_vectors() {",
        "    return {",
    ]
    for name, plain, packed in vectors:
        lines.append('        {"%s", %s, %s},' % (name, cpp_bytes(plain), cpp_bytes(packed)))
    lines += ["    };", "}"]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


